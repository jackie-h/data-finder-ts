"""Write the data of the TPC-BiH specs as CSV files, one per table, to the directory given.

The data is generated by the Python project (datafinder_examples_tests.tpch_bih_generator, which follows Appendix A of the
report, at scale factor 0.001 with 1000 scenarios and seed 1) on top of DuckDB's TPC-H extension, which this installs.

Usage: uv run python scripts/tpch_bih_data.py <directory>
"""
import shutil
import sys
from pathlib import Path

import duckdb

from datafinder_examples_tests.tpch_bih_data import csv_dir


def main(target: str) -> None:
    duckdb.execute("INSTALL tpch")
    out = Path(target)
    out.mkdir(parents=True, exist_ok=True)
    for source in sorted(csv_dir().glob("tpch_bih_benchmark_*.csv")):
        shutil.copy(source, out / source.name)
    print(f"... wrote {len(list(out.glob('*.csv')))} tables to {out}")


if __name__ == "__main__":
    main(sys.argv[1])
