"""
Generate the TypeScript TPC-BiH specs from the Python project's `datafinder_examples_tests.tpch_bih_specs`.

A benchmark case (tpch_bih_cases.py) has the values of its parameters and the rows its SQL returns on the generated data; its
finder query is in tpch_bih_queries.py, or the reason the finders cannot ask it as the report does. This translates each query
with the translator of generate_spec_tests.py, with the case's parameters filled in, and writes:

    tests/specs/cases/tpch-bih.ts      the cases (queries, expected columns and rows), run by tests/tpch-bih-specs.test.ts
    tests/specs/tpch-bih-tables.ts     the DDL of the tables (tpch_bih_db.TABLES)

The data the cases run on is written by scripts/tpch_bih_data.py.

Usage: uv run python scripts/generate_tpch_bih_specs.py
"""
import ast
import re
import datetime
import decimal
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import generate_spec_tests as base  # noqa: E402
from generate_spec_tests import OUT_DIR, SPEC_DIR, Translator, js_str, ts_rows  # noqa: E402

from datafinder_examples_tests import tpch_bih_queries  # noqa: E402
from datafinder_examples_tests.tpch_bih_cases import CASES  # noqa: E402
from datafinder_examples_tests.tpch_bih_db import TABLES  # noqa: E402
from datafinder_examples_tests.tpch_bih_queries import QUERIES, Unsupported  # noqa: E402

BANNER = '// Generated by scripts/generate_tpch_bih_specs.py from datafinder_examples_tests.tpch_bih_specs. Do not edit.'


class TpchTranslator(Translator):
    """The translator, which also knows a query's own names: its finders `q`, its parameters `p`, and the helpers it calls."""

    def __init__(self) -> None:
        super().__init__()
        self.model_used.add('DateOnly')

    def visit_Compare(self, node: ast.Compare) -> str:
        (op,), (right,) = node.ops, node.comparators
        if isinstance(op, (ast.Is, ast.IsNot)):   # `x is None`: a plain value
            return f'({self.expr(node.left)} {"===" if isinstance(op, ast.Is) else "!=="} {self.expr(right)})'
        if isinstance(node.left, ast.Name) and isinstance(op, (ast.Eq, ast.NotEq)) \
                and (node.left.id in self.plain or isinstance(right, ast.Constant)):   # a name against a literal is a plain value
            return f'({self.expr(node.left)} {"===" if isinstance(op, ast.Eq) else "!=="} {self.expr(right)})'
        return super().visit_Compare(node)


def ts_param(value) -> str:
    """A parameter of a case, as the TypeScript value a query is given."""
    if isinstance(value, datetime.datetime):
        return f'new Date(Date.UTC({value.year}, {value.month - 1}, {value.day}, {value.hour}, {value.minute}, {value.second}))'
    if isinstance(value, datetime.date):
        return f"new DateOnly('{value.isoformat()}T00:00:00Z')"
    if isinstance(value, (list, tuple)):
        return '[' + ', '.join(ts_param(v) for v in value) + ']'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, str):
        return js_str(value)
    if isinstance(value, (int, float, decimal.Decimal)):
        return repr(value if not isinstance(value, decimal.Decimal) else float(value))
    raise NotImplementedError(repr(value))


def function_source(translator: Translator, stmt: ast.FunctionDef) -> str:
    """A module-level helper of the queries, as a TypeScript function. Arguments with a default or a type are plain values."""
    names = [a.arg for a in stmt.args.args]
    defaults = [None] * (len(names) - len(stmt.args.defaults)) + list(stmt.args.defaults)
    translator.signatures[stmt.name] = names
    plain_before = set(translator.plain)
    translator.plain = {a.arg for a, d in zip(stmt.args.args, defaults) if d is not None or a.annotation is not None}
    params = ', '.join(f'{a.arg}: any' + (f' = {translator.expr(d)}' if d is not None else '') for a, d in zip(stmt.args.args, defaults))
    declared = set(names)
    translator.callables = set(names)
    translator.local_functions = {}

    def block(body: list[ast.stmt], indent: str) -> list[str]:
        lines: list[str] = []
        for inner in body:
            if isinstance(inner, ast.Expr) and isinstance(inner.value, ast.Constant):
                continue   # a docstring
            if isinstance(inner, ast.Expr):
                lines.append(f'{indent}{translator.expr(inner.value)};')
            elif isinstance(inner, ast.Assign) and len(inner.targets) == 1 and isinstance(inner.targets[0], ast.Name):
                name = inner.targets[0].id
                keyword = '' if name in declared else 'let '
                declared.add(name)
                lines.append(f'{indent}{keyword}{name} = {translator.expr(inner.value)};')
            elif isinstance(inner, ast.Assign) and isinstance(inner.targets[0], ast.Tuple) and isinstance(inner.value, ast.Tuple):
                targets = [t.id for t in inner.targets[0].elts]
                declared.update(targets)
                lines.append(f'{indent}const [{", ".join(targets)}] = [{", ".join(translator.expr(v) for v in inner.value.elts)}];')
            elif isinstance(inner, ast.Assign) and isinstance(inner.targets[0], ast.Tuple):   # a, b, c = when: unpacked from a value
                targets = [t.id for t in inner.targets[0].elts]
                declared.update(targets)
                lines.append(f'{indent}const [{", ".join(targets)}] = {translator.expr(inner.value)};')
            elif isinstance(inner, ast.FunctionDef):   # a function of the helper's own, which a query step calls
                positional = [a.arg for a in inner.args.args]
                vararg = inner.args.vararg.arg if inner.args.vararg else None
                kwonly = [a.arg for a in inner.args.kwonlyargs]
                translator.local_functions[inner.name] = (positional, vararg, kwonly)
                declared.add(inner.name)
                parameters = [f'{n}: any' for n in positional] + ([f'{vararg}: any[]'] if vararg else []) \
                    + [f'{a.arg}: any = {translator.expr(d) if d is not None else "undefined"}'
                       for a, d in zip(inner.args.kwonlyargs, inner.args.kw_defaults)]
                lines.append(f'{indent}const {inner.name} = ({", ".join(parameters)}) => {{')
                lines += block(inner.body, indent + '  ')
                lines.append(f'{indent}}};')
            elif isinstance(inner, ast.Return):
                lines.append(f'{indent}return {translator.expr(inner.value)};')
            elif isinstance(inner, ast.If):
                lines.append(f'{indent}if ({translator.expr(inner.test)}) {{')
                lines += block(inner.body, indent + '  ')
                orelse = inner.orelse
                while len(orelse) == 1 and isinstance(orelse[0], ast.If):   # elif
                    lines.append(f'{indent}}} else if ({translator.expr(orelse[0].test)}) {{')
                    lines += block(orelse[0].body, indent + '  ')
                    orelse = orelse[0].orelse
                if orelse:
                    lines.append(f'{indent}}} else {{')
                    lines += block(orelse, indent + '  ')
                lines.append(f'{indent}}}')
            else:
                raise NotImplementedError(ast.dump(inner))
        return lines

    body = '\n'.join(block(stmt.body, '  '))
    translator.callables = set()
    translator.local_functions = {}
    translator.plain = plain_before
    return f'export function {stmt.name}({params}) {{\n{body}\n}}'


def module_value(name: str):
    return getattr(tpch_bih_queries, name)


def constant_source(translator: Translator, stmt: ast.Assign) -> str:
    name = stmt.targets[0].id
    if isinstance(stmt.value, ast.Constant):
        return f'export const {name} = {translator.expr(stmt.value)};'
    return f'export const {name} = {ts_param(module_value(name))};'   # _NOW = CURRENT_SYS


def query_lambdas(tree: ast.Module) -> dict[str, ast.Lambda]:
    """The query of each `"id": FinderQuery([...], lambda q, p: ...)` of the module's dicts."""
    found: dict[str, ast.Lambda] = {}
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Dict):
            for key, value in zip(stmt.value.keys, stmt.value.values):
                if isinstance(value, ast.Call) and getattr(value.func, 'id', None) == 'FinderQuery':
                    found[ast.literal_eval(key)] = value.args[1]
    return found


# What a query needs that the translator has no TypeScript for, until the relation steps of a result are ported.
UNPORTED_REASON = 'the query reads results as relations (filter, extend, select, group_by, join, exists), which is not ported yet'


def main() -> None:
    source = open(os.path.join(SPEC_DIR, 'tpch_bih_queries.py')).read()
    tree = ast.parse(source)
    translator = TpchTranslator()
    lambdas = query_lambdas(tree)

    helpers = [s for s in tree.body if isinstance(s, ast.FunctionDef) and s.name.startswith('_')]
    translator.helpers.update(h.name for h in helpers)
    for helper in helpers:
        translator.signatures[helper.name] = [a.arg for a in helper.args.args]
    consts = [constant_source(translator, s) for s in tree.body
              if isinstance(s, ast.Assign) and isinstance(s.targets[0], ast.Name) and s.targets[0].id in ('_NOW', '_FOREVER_START', '_FOREVER_END')]
    functions = []
    failed: dict[str, str] = {}   # helpers that could not be translated yet
    for helper in helpers:
        try:
            functions.append(function_source(translator, helper))
        except NotImplementedError as error:
            failed[helper.name] = str(error)
    # a helper that calls one that could not be translated cannot be either
    for _ in range(len(functions)):
        broken = [(f, name) for f in functions for name in failed if re.search(rf'\b{re.escape(name)}\(', f)]
        if not broken:
            break
        for source, name in broken:
            functions.remove(source)
            failed[re.match(r'export function (\w+)', source).group(1)] = failed[name]

    blocks = []
    for case_id, case in CASES.items():
        entry = QUERIES[case_id]
        if isinstance(entry, Unsupported):
            columns = [str(c) for c in case.select]
            query = f'_q => {{ throw new Error({js_str(entry.reason)}); }}'
            fields = [f'columns: [{", ".join(js_str(c) for c in columns)}]', 'rows: []', f'skip: {js_str(entry.reason)}']
        else:
            lam = lambdas[case_id]
            translator.plain = set()
            try:
                body = translator.expr(lam.body)
                broken = [name for name in failed if re.search(rf'\b{re.escape(name)}\b', body)]
                if broken:
                    raise NotImplementedError(failed[broken[0]])
            except NotImplementedError as error:
                # a construct of the query that the translator has no TypeScript for yet: the case is listed, skipped
                reason = UNPORTED_REASON
                print(f'... {case_id} is skipped: {str(error)[:300]}')
                columns = [str(c) for c in case.select]
                blocks.append(f"  {{\n    name: {js_str(case_id)},\n    query: _q => {{ throw new Error({js_str(reason)}); }},\n"
                              f"    expected: {{ columns: [{', '.join(js_str(c) for c in columns)}], rows: [], skip: {js_str(reason)} }},\n  }},\n")
                continue
            params = ', '.join(f'{k}: {ts_param(v)}' for k, v in case.parameters.items())
            used = 'p.' in body or ', p)' in body or '(p,' in body or ', p,' in body
            query = f'q => {{\n      const p = {{ {params} }};\n      return {body};\n    }}' if case.parameters and used else f'q => {body}'
            fields = [f"columns: [{', '.join(js_str(c) for c in entry.columns)}]", f'rows: {ts_rows(case.expected())}']
            if case.approximate:
                fields.append('approximate: true')
        blocks.append(f"  {{\n    name: {js_str(case_id)},\n    query: {query},\n    expected: {{ {', '.join(fields)} }},\n  }},\n")

    if any('new Interval(' in block for block in blocks):   # an expected interval
        translator.model_used.add('Interval')
    header = [BANNER, "import { ts, type SpecCase } from '../../spec-harness';"]
    if translator.model_used:
        header.append(f"import {{ {', '.join(sorted(translator.model_used))} }} from '../../../src/model/relational';")
    if translator.used:
        header.append(f"import {{ {', '.join(sorted(translator.used))} }} from '../../../src/datafinder';")
    header.append("import type { TpchBihFinders } from '../../tpch-bih-finders';")
    cases_src = ('\n'.join(header) + '\n\n' + '\n'.join(consts) + '\n\n' + '\n\n'.join(functions) + '\n\n'
                 + 'export const TPCH_BIH_SPECS: SpecCase<TpchBihFinders>[] = [\n' + ''.join(blocks) + '];\n')
    os.makedirs(os.path.join(OUT_DIR, 'cases'), exist_ok=True)
    tables = BANNER + '\n/** The DDL of the TPC-BiH tables, by table name (tpch_bih_db.TABLES). */\nexport const TPCH_BIH_TABLES: Record<string, string> = {\n' \
        + ''.join(f'  {name}: {js_str(columns)},\n' for name, columns in TABLES.items()) + '};\n'
    for out, src in ((os.path.join(OUT_DIR, 'cases', 'tpch-bih.ts'), cases_src),
                     (os.path.join(OUT_DIR, 'tpch-bih-tables.ts'), tables)):
        with open(out, 'w') as f:
            f.write(src)
        print(f'... wrote {os.path.relpath(out, base.ROOT)}')


if __name__ == '__main__':
    main()
